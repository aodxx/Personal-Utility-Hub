import { chromium, devices } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const fixtureDir = path.join(root, 'tests/fixtures/audio');
const outputJson = path.join(root, 'docs/audio-capability-matrix.json');
const outputMd = path.join(root, 'docs/audio-codec-capability-matrix.md');
const profiles = [
  { name: 'Desktop Chromium', viewport: { width: 1280, height: 900 }, userAgent: undefined },
  { name: 'Android Chromium', ...devices['Pixel 5'], viewport: { width: 360, height: 740 } },
  { name: 'Pixel 7 class', ...devices['Pixel 7'], viewport: { width: 412, height: 915 } },
];
const fixtures = [
  { file: 'mono-44k.wav', mime: 'audio/wav', label: 'WAV PCM mono 44.1 kHz' },
  { file: 'speech.mp3', mime: 'audio/mpeg', label: 'MP3 mono 44.1 kHz' },
  { file: 'voice.m4a', mime: 'audio/mp4', label: 'M4A AAC stereo 48 kHz' },
  { file: 'speech.ogg', mime: 'audio/ogg', label: 'OGG Vorbis mono 44.1 kHz' },
  { file: 'voice.webm', mime: 'audio/webm', label: 'WebM Opus stereo 48 kHz' },
];
const results = [];
for (const profile of profiles) {
  const browser = await chromium.launch({ headless: true });
  const context = await browser.newContext({ viewport: profile.viewport, userAgent: profile.userAgent });
  const page = await context.newPage();
  await page.setContent('<input id="file" type="file"><audio id="audio" controls></audio>');
  for (const fixture of fixtures) {
    const fixturePath = path.join(fixtureDir, fixture.file);
    await page.setInputFiles('#file', fixturePath);
    const result = await page.evaluate(async ({ mime }) => {
      const input = document.querySelector('#file');
      const audio = document.querySelector('#audio');
      const file = input.files[0];
      const url = URL.createObjectURL(file);
      audio.src = url;
      audio.muted = true;
      const playback = await new Promise((resolve) => {
        const finish = (value) => { audio.removeEventListener('loadedmetadata', onLoaded); audio.removeEventListener('error', onError); resolve(value); };
        const onLoaded = () => finish({ status: 'loaded', duration: audio.duration, canPlay: audio.canPlayType(mime) || 'unknown' });
        const onError = () => finish({ status: 'error', message: audio.error?.message || 'media error' });
        audio.addEventListener('loadedmetadata', onLoaded, { once: true });
        audio.addEventListener('error', onError, { once: true });
        audio.load();
      });
      let decode = { status: 'unavailable' };
      try {
        const context = new AudioContext();
        const bytes = await file.arrayBuffer();
        const buffer = await context.decodeAudioData(bytes.slice(0));
        decode = { status: 'decoded', duration: buffer.duration, channels: buffer.numberOfChannels, sampleRate: buffer.sampleRate };
        await context.close();
      } catch (error) {
        decode = { status: 'error', name: error?.name || 'Error', message: error?.message || String(error) };
      }
      let play = { status: 'not-attempted' };
      try {
        await audio.play();
        play = { status: 'started' };
        audio.pause();
      } catch (error) {
        play = { status: 'blocked-or-error', name: error?.name || 'Error', message: error?.message || String(error) };
      }
      URL.revokeObjectURL(url);
      return { playback, decode, play };
    }, { mime: fixture.mime });
    results.push({ profile: profile.name, ...fixture, ...result });
  }
  await browser.close();
}
await fs.writeFile(outputJson, `${JSON.stringify(results, null, 2)}\n`);
const status = (value) => value === 'decoded' || value === 'loaded' || value === 'started' ? 'supported' : value === 'error' ? 'unsupported-or-browser-dependent' : 'unknown';
const rows = results.map((result) => `| ${result.profile} | ${result.label} | ${status(result.playback.status)} | ${status(result.decode.status)} | ${status(result.play.status)} | ${result.decode.channels ?? '—'} | ${result.decode.sampleRate ?? '—'} |`);
const markdown = `# Audio Codec Capability Matrix\n\nGenerated by \`scripts/audio-capability-matrix.mjs\` against the local Chromium runtime profiles. A status of **supported** means the specific fixture completed that check in the stated profile; it is not a universal browser guarantee.\n\n| Profile | Input | <audio> playback | decodeAudioData | play() attempt | Channels | Sample rate |\n|---|---|---|---|---|---:|---:|\n${rows.join('\n')}\n\n## Policy\n\nThe matrix is evidence for the tested Chromium runtime only. UI copy must use “supported in this tested profile” or “browser-dependent” rather than promising universal codec support. If native decode fails, the application should present a meaningful error and suggest WAV or MP3 as an alternative; it must not silently claim that an unsupported input works.\n\nNo remote decoder or cloud transcoding is used by this matrix.\n`;
await fs.writeFile(outputMd, markdown);
for (const result of results) console.log(`${result.profile} | ${result.file} | playback=${result.playback.status} | decode=${result.decode.status} | play=${result.play.status}`);
